"""
Модель стандартной атмосферы ISA.
Рассчитывает температуру, давление и плотность воздуха на заданной высоте.
"""

import numpy as np


def get(z):
    """
    Возвращает (T, p, rho) для высоты z [м].
    
    Параметры:
        z: высота в метрах (число или массив)
    
    Возвращает:
        T: температура в Кельвинах
        p: давление в Паскалях
        rho: плотность воздуха в кг/м³
    """
    # Константы стандартной атмосферы
    T0 = 288.15      # Температура на уровне моря, K
    L = 6.5e-3       # Температурный градиент, K/м
    g = 9.80665      # Ускорение свободного падения, м/с²
    R = 287.05       # Газовая постоянная воздуха, Дж/(кг·К)
    p0 = 101325.0    # Давление на уровне моря, Па

    # Преобразуем вход в массив для векторизации
    z = np.atleast_1d(z)
    T = np.zeros_like(z, dtype=float)
    p = np.zeros_like(z, dtype=float)

    # Маски для тропосферы и стратосферы
    trop_mask = z < 11000
    strat_mask = ~trop_mask

    # Тропосфера (0-11 км): температура линейно падает
    T[trop_mask] = T0 - L * z[trop_mask]
    p[trop_mask] = p0 * (T[trop_mask] / T0) ** (g / (R * L))

    # Стратосфера (>11 км): температура постоянна
    T11 = T0 - L * 11000
    p11 = p0 * (T11 / T0) ** (g / (R * L))
    T[strat_mask] = T11
    p[strat_mask] = p11 * np.exp(-g * (z[strat_mask] - 11000) / (R * T11))

    # Плотность из уравнения состояния идеального газа
    rho = p / (R * T)

    # Если на входе был скаляр, возвращаем скаляры
    if len(z) == 1:
        return float(T[0]), float(p[0]), float(rho[0])
    return T, p, rho
