"""
Модель профиля ветра.
Рассчитывает 3D-скорость ветра (u, v, w) на заданной высоте.
"""

import numpy as np


def get(z, wind_type='standard'):
    """
    Возвращает компоненты ветра (u, v, w) для высоты z [м].
    
    Параметры:
        z: высота в метрах (число или массив)
        wind_type: тип профиля ветра
            - 'standard': стандартный профиль (лог. + джет)
            - 'strong': усиленный ветер (для Monte Carlo)
            - 'weak': слабый ветер (для Monte Carlo)
    
    Возвращает:
        u: зональная компонента (восток-запад), м/с
        v: меридиональная компонента (север-юг), м/с
        w: вертикальная компонента, м/с (обычно мала)
    """
    # Параметры логарифмического закона
    u_star = 0.4
    z0 = 0.1
    kappa = 0.4
    
    # Масштабный коэффициент для разных сценариев
    scale = {'standard': 1.0, 'strong': 1.5, 'weak': 0.5}.get(wind_type, 1.0)
    
    z = np.atleast_1d(z)
    u = np.zeros_like(z, dtype=float)
    v = np.zeros_like(z, dtype=float)
    w = np.zeros_like(z, dtype=float)
    
    mask1 = z < 1000
    mask2 = (z >= 1000) & (z < 10000)
    mask3 = z >= 10000
    
    # Приземный слой: логарифмический профиль
    u[mask1] = (u_star / kappa) * np.log(np.maximum(z[mask1], z0) / z0)
    
    # Тропосфера: линейный рост до джета
    u[mask2] = 10 + 2.5 * (z[mask2] - 1000) / 9000
    
    # Стратосфера: струйное течение
    u[mask3] = 35 - 0.5 * (z[mask3] - 10000) / 1000
    
    # Применяем масштаб и ограничиваем
    u = np.clip(u * scale, 0, 75)
    
    # Меридиональная компонента (зависит от высоты)
    v = 0.3 * u * np.sin(z / 3000)
    
    # Вертикальная компонента (мала, ~0.01-0.05 м/с)
    # В реальных условиях связана с конвекцией и орографией
    w = 0.02 * np.sin(z / 2000) * np.exp(-z / 10000)
    
    if len(z) == 1:
        return float(u[0]), float(v[0]), float(w[0])
    return u, v, w