"""
Модель профиля ветра.
Рассчитывает скорость ветра на заданной высоте.
"""

import numpy as np


def get(z):
    """
    Возвращает компоненты ветра (u, v) для высоты z [м].
    
    Параметры:
        z: высота в метрах (число или массив)
    
    Возвращает:
        u: зональная компонента (восток-запад), м/с
        v: меридиональная компонента (север-юг), м/с
    
    Модель:
    - 0-1 км: логарифмический закон (приземный слой)
    - 1-10 км: линейный рост (тропосфера)
    - >10 км: струйное течение (джет)
    """
    # Параметры логарифмического закона
    u_star = 0.4    # Скорость трения, м/с
    z0 = 0.1        # Параметр шероховатости, м
    kappa = 0.4     # Постоянная Кармана
    
    # Преобразуем вход в массив
    z = np.atleast_1d(z)
    u = np.zeros_like(z, dtype=float)
    v = np.zeros_like(z, dtype=float)
    
    # Маски для разных высотных диапазонов
    mask1 = z < 1000                    # Приземный слой
    mask2 = (z >= 1000) & (z < 10000)   # Тропосфера
    mask3 = z >= 10000                  # Стратосфера
    
    # Приземный слой: логарифмический профиль
    u[mask1] = (u_star / kappa) * np.log(np.maximum(z[mask1], z0) / z0)
    
    # Тропосфера: линейный рост
    u[mask2] = 10 + 2.5 * (z[mask2] - 1000) / 9000
    
    # Стратосфера: струйное течение
    u[mask3] = 35 - 0.5 * (z[mask3] - 10000) / 1000
    
    # Ограничиваем скорость ветра
    u = np.clip(u, 0, 50)
    
    # Меридиональная компонента (для 2D дрейфа)
    v = 0.3 * u * np.sin(z / 3000)
    
    # Если на входе был скаляр, возвращаем скаляры
    if len(z) == 1:
        return float(u[0]), float(v[0])
    return u, v